#!/usr/bin/env node
// Bundle the emitted declaration files of src/TacPhoneMain.ts into a single
// dist/TacPhoneMain.d.ts that apps can copy into their own project.
//
// Runs after `vite build` (the dts plugin emits the per-file declarations).
//
// API Extractor intentionally only emits declarations reachable from exports,
// so the `declare global { interface Window { ... } }` block from
// src/TacPhoneMain.ts is preserved and appended again after bundling.

import { existsSync } from 'node:fs'
import { readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Extractor, ExtractorConfig } from '@microsoft/api-extractor'
import ts from 'typescript'
import { SHARED_MODULES } from '../shared-modules.js'

const mainDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const distDir = join(mainDir, 'dist')
const apiFile = join(distDir, 'TacPhoneMain.d.ts')

const banner = `// Generated by ACE_TacPhone_Main. Do not edit this file by hand.
// Edit src/TacPhoneMain.ts in ACE_TacPhone_Main instead.
`

function displayPath(path) {
    return relative(mainDir, path).replaceAll('\\', '/')
}

function findDeclareGlobalBlocks(sourceFile) {
    const blocks = []

    sourceFile.forEachChild(node => {
        if (ts.isModuleDeclaration(node) && (node.flags & ts.NodeFlags.GlobalAugmentation)) {
            blocks.push(node.getText(sourceFile))
        }
    })

    if (blocks.length === 0) {
        throw new Error('src/TacPhoneMain.ts does not emit a "declare global" block.')
    }

    return blocks
}

function getImportBindings(importDeclaration) {
    const bindings = []
    const clause = importDeclaration.importClause
    if (!clause) return bindings

    if (clause.name) bindings.push(clause.name.text)

    if (clause.namedBindings) {
        if (ts.isNamespaceImport(clause.namedBindings)) {
            bindings.push(clause.namedBindings.name.text)
        } else if (ts.isNamedImports(clause.namedBindings)) {
            for (const element of clause.namedBindings.elements) {
                bindings.push(element.name.text)
            }
        }
    }

    return bindings
}

function getDeclaredNames(sourceFile) {
    const names = new Set()

    sourceFile.forEachChild(node => {
        if (ts.isImportDeclaration(node)) {
            for (const name of getImportBindings(node)) names.add(name)
            return
        }

        if (
            ts.isClassDeclaration(node)
            || ts.isInterfaceDeclaration(node)
            || ts.isTypeAliasDeclaration(node)
            || ts.isEnumDeclaration(node)
            || ts.isFunctionDeclaration(node)
        ) {
            if (node.name) names.add(node.name.text)
            return
        }

        if (ts.isVariableStatement(node)) {
            for (const declaration of node.declarationList.declarations) {
                if (ts.isIdentifier(declaration.name)) names.add(declaration.name.text)
            }
        }
    })

    return names
}

function collectNeededImports(sourceFile, globalBlocks) {
    const globalText = globalBlocks.join('\n')
    const imports = []

    sourceFile.forEachChild(node => {
        if (!ts.isImportDeclaration(node)) return

        const specifier = node.moduleSpecifier
        if (!ts.isStringLiteral(specifier) || specifier.text.startsWith('.')) return

        const bindings = getImportBindings(node)
        const usedBindings = bindings.filter(name => new RegExp(`\\b${name}\\b`).test(globalText))
        if (usedBindings.length === 0) return

        imports.push({
            text: node.getText(sourceFile),
            bindings: usedBindings,
        })
    })

    return imports
}

async function bundleDeclarations() {
    if (!existsSync(apiFile)) {
        throw new Error(
            `${displayPath(apiFile)} does not exist. Run "vite build" before bundling the API types.`,
        )
    }

    const preBundleSource = await readFile(apiFile, 'utf8')
    const preBundleFile = ts.createSourceFile(
        'TacPhoneMain.d.ts',
        preBundleSource,
        ts.ScriptTarget.Latest,
        true,
    )
    const globalBlocks = findDeclareGlobalBlocks(preBundleFile)
    const neededImports = collectNeededImports(preBundleFile, globalBlocks)

    const configObject = {
        projectFolder: mainDir,
        mainEntryPointFilePath: apiFile,
        compiler: {
            tsconfigFilePath: join(mainDir, 'tsconfig.app.json'),
        },
        apiReport: {
            enabled: false,
        },
        docModel: {
            enabled: false,
        },
        dtsRollup: {
            enabled: true,
            publicTrimmedFilePath: apiFile,
        },
        tsdocMetadata: {
            enabled: false,
        },
        messages: {
            compilerMessageReporting: {
                default: { logLevel: 'none' },
            },
            extractorMessageReporting: {
                default: { logLevel: 'none' },
            },
            tsdocMessageReporting: {
                default: { logLevel: 'none' },
            },
        },
    }

    const config = ExtractorConfig.prepare({
        configObject,
        configObjectFullPath: join(mainDir, 'api-extractor.json'),
        packageJsonFullPath: join(mainDir, 'package.json'),
    })

    const result = Extractor.invoke(config, {
        localBuild: false,
        showVerboseMessages: false,
        showDiagnostics: false,
    })

    if (!result.succeeded) {
        throw new Error('API Extractor failed to bundle the TacPhone API declarations.')
    }

    const bundledSource = (await readFile(apiFile, 'utf8'))
        .replace(/\r?\n?export \{\s*\}\s*$/, '')
        .trimEnd()
    const bundledFile = ts.createSourceFile(
        'TacPhoneMain.d.ts',
        bundledSource,
        ts.ScriptTarget.Latest,
        true,
    )
    const declaredNames = getDeclaredNames(bundledFile)

    const importTexts = []
    for (const neededImport of neededImports) {
        if (neededImport.bindings.some(name => declaredNames.has(name))) continue

        importTexts.push(neededImport.text)
        for (const name of neededImport.bindings) declaredNames.add(name)
    }

    const output = [
        banner,
        ...importTexts,
        bundledSource.trimEnd(),
        '',
        ...globalBlocks,
        '',
    ].join('\n')

    await writeFile(apiFile, output)
}

async function removeStaleDeclarations(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name)

        if (entry.isDirectory()) {
            await removeStaleDeclarations(path)
            continue
        }

        if (resolve(path) === apiFile) continue

        if (entry.name.endsWith('.d.ts') || entry.name.endsWith('.d.ts.map')) {
            await rm(path)
        }
    }
}

async function verifyDeclarations() {
    const program = ts.createProgram([apiFile], {
        target: ts.ScriptTarget.ES2023,
        module: ts.ModuleKind.ESNext,
        moduleResolution: ts.ModuleResolutionKind.Bundler,
        skipLibCheck: false,
        noEmit: true,
    })

    const sourceFile = program.getSourceFile(apiFile)
    if (!sourceFile) {
        throw new Error(`TypeScript could not load ${displayPath(apiFile)}.`)
    }

    const diagnostics = [
        ...program.getSyntacticDiagnostics(sourceFile),
        ...program.getSemanticDiagnostics(sourceFile),
    ].filter(diagnostic => diagnostic.file?.fileName === sourceFile.fileName)

    if (diagnostics.length > 0) {
        const formatted = ts.formatDiagnosticsWithColorAndContext(diagnostics, {
            getCanonicalFileName: fileName => fileName,
            getCurrentDirectory: () => mainDir,
            getNewLine: () => '\n',
        })
        throw new Error(`${displayPath(apiFile)} has type errors:\n${formatted}`)
    }

    const checker = program.getTypeChecker()
    const windowSymbol = checker
        .getSymbolsInScope(sourceFile, ts.SymbolFlags.Interface)
        .find(symbol => symbol.getName() === 'Window')

    if (!windowSymbol) {
        throw new Error('The generated declaration file does not declare the global Window interface.')
    }

    const windowType = checker.getDeclaredTypeOfSymbol(windowSymbol)
    const windowProperties = new Set(windowType.getProperties().map(property => property.getName()))
    const expected = [
        'Networking',
        'AppDirectory',
        'TacPhoneUtils',
        ...SHARED_MODULES.map(({ global }) => global),
    ]
    const missing = expected.filter(name => !windowProperties.has(name))

    if (missing.length > 0) {
        throw new Error(
            `${displayPath(apiFile)} is missing window globals: ${missing.join(', ')}. `
            + 'Add them to src/TacPhoneMain.ts.',
        )
    }
}

try {
    await bundleDeclarations()
    await removeStaleDeclarations(distDir)
    await verifyDeclarations()
    console.log(`OK  ${displayPath(apiFile)} (bundled host API declarations)`)
} catch (error) {
    console.error(`FAIL ${error.message}`)
    process.exitCode = 1
}
